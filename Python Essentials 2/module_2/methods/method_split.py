# El método split() divide la cadena y 
# crea una lista de todas las subcadenas detectadas.

# El método asume que las subcadenas están delimitadas 
# por espacios en blanco, los espacios no participan 
# en la operación y no se copian en la lista resultante.

# Si la cadena está vacía, la lista resultante también está vacía.
print("phi       chi\npsi".split()) #-> ['phi', 'chi', 'psi']