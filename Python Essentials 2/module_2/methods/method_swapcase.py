# El método swapcase() crea una nueva cadena intercambiando 
# todas las letras por mayúsculas o minúsculas dentro 
# de la cadena original: los caracteres en mayúscula 
# se convierten en minúsculas y viceversa.

# Todos los demás caracteres permanecen intactos.
print("Yo solo sé que no sé nada".swapcase()) #-> yO SOLO SÉ QUE NO SÉ NADA