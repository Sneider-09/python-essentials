# Por último, pero no menos importante, el método upper() 
# hace una copia de la cadena de origen, reemplaza todas 
# las letras minúsculas con sus equivalentes en mayúsculas, 
# y devuelve la cadena como resultado.
print("Yo solo sé que no sé nada. Parte 2.".upper()) #-> YO SOLO SÉ QUE NO SÉ NADA. PARTE 2.