# Exponenciacion
print('Exponenciacion')
print(2 ** 3)
print(2 ** 3.)
print(2. ** 3)
print(2. ** 3.)

# Multiplicación
print('Multiplicación')
print(2 * 3)
print(2 * 3.)
print(2. * 3)
print(2. * 3.)

# División
print('División')
print(6 / 3)
print(6 / 3.)
print(6. / 3)
print(6. / 3.)

# División entera
print('División entera')
print(6 // 3)
print(6 // 3.)
print(6. // 3)
print(6. // 3.)

# Residuo (módulo)
print('Residuo (módulo)')
print(14 % 4)
print(12 % 4.5)

# Suma
print('Suma')
print(-4 + 4)
print(-4. + 8)

# Resta
print('Resta')
print(-4 - 4)
print(4. - 8)
print(-1.1)

# Operadores y sus prioridades
print('Operadores y sus prioridades')
print(2 + 3 * 5)

# Operadores y sus enlaces
